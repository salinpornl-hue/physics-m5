import streamlit as st

# ตั้งค่าหน้าเว็บ
st.set_page_config(page_title="แบบฝึกหัดฟิสิกส์: เรื่องคลื่น", page_icon="🌊", layout="centered")

st.title("🌊 คลังโจทย์แบบฝึกหัดฟิสิกส์: เรื่องคลื่น")
st.markdown("รวบรวมโจทย์ปัญหาสำหรับฝึกฝนความเข้าใจเรื่องคุณสมบัติของคลื่น อัตราเร็ว ความถี่ และการแทรกสอด")
st.divider()

# วางโจทย์ทั้งหมดของคุณลงในตัวแปรนี้ (ผมใส่เป็นตัวอย่างไว้ให้บางส่วน)
# ข้อความที่มีสมการคณิตศาสตร์ ให้คงสัญลักษณ์ $ ไว้ Streamlit จะเรนเดอร์เป็นสมการให้สวยงาม
raw_questions = """
เชือกเส้นหนึ่งสั่นด้วยความถี่ค่าหนึ่ง ทำให้เกิดคลื่นต่อเนื่องเคลื่อนที่ไปทางขวาดังรูปที่ (1) เป็นภาพถ่ายการสั่นของเส้นเชือกในช่วงหนึ่งและในขณะที่คลื่นเคลื่อนที่ไป อนุภาคของเส้นเชือก การเคลื่อนที่ ขึ้น - ลง ซึ่งเมื่อเขียนกราฟแสดงความสัมพันธ์ระหว่างการกระจัดกับเวลาจะได้ดัง รูปที่ (2) จงหาอัตราเร็วของคลื่นบนเส้นเชือก
ในการสั่นเชือกที่มีความยาวมากเส้นหนึ่ง ปรากฏว่าหลังจากการสั่น 0.5 วินาที ได้คลื่นดังรูป จงหาอัตราเร็วของคลื่นบนเชือกเส้นนี้
คลื่นดลกำลังเคลื่อนที่จากซ้ายไปขวาด้วยอัตราเร็วคงที่ 20 ช่อง/วินาที ณ เวลาเริ่มต้น $t = 0$ เห็นคลื่นดังรูป เขียนรูปร่างคลื่น เมื่อเวลา 0.1, 0.2, 0.3, 0.4 และ 0.5 วินาที
คลื่นต่อเนื่องขบวนหนึ่งมีอัตราเร็ว 20 เมตร/วินาที เกิดจากแหล่งกำเนิดซึ่งสั่นด้วยความถี่ 40 เฮิรตซ์ ก. จุด 2 จุดบนคลื่นห่างกัน 10 เซนติเมตร จะมีเฟสต่างกันเท่าไร ข. จุด 2 จุดบนคลื่นมีเฟสต่างกัน $90^{\circ}$ จะห่างกันเท่าไร
"""

# แยกโจทย์แต่ละข้อด้วยการตัดบรรทัด (Enter)
questions = [q.strip() for q in raw_questions.strip().split('\n') if q.strip()]

# วนลูปเพื่อแสดงโจทย์แต่ละข้อ
for i, q in enumerate(questions):
    st.markdown(f"**ข้อที่ {i+1}.** {q}")
    
    # เพิ่มกล่องข้อความจำลองให้ผู้ใช้พิมพ์ทดคำตอบ (ไม่ได้เก็บข้อมูลจริง)
    st.text_input(f"คำตอบข้อ {i+1}", key=f"ans_{i}")
    st.divider()

st.caption("พัฒนาโดยใช้ Streamlit 🎈")
