def check_answer(user_input: str, expected: float, tol_pct: float) -> bool:
    """Return True if user_input is within tolerance of expected."""
    try:
        val = float(user_input.strip().replace(",", "."))
    except ValueError:
        return False
    if expected == 0:
        return abs(val) < 0.5
    if tol_pct == 0:
        return abs(val - expected) < 0.5
    return abs(val - expected) / abs(expected) * 100 <= tol_pct
